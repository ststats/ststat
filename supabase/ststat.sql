    (select count(*) || '/' || coalesce(sum(hashtextextended(r::text, 0)::numeric), 0)
       from (select category_id, name from public.elo_categories) r),
    (select count(*) || '/' || coalesce(sum(hashtextextended(r::text, 0)::numeric), 0)
