create or replace function public.admin_dashboard_stats()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  result jsonb;
  elo_total bigint;
  daily_date date;
  job_name text;
  job_status text;
  job_finished timestamptz;
begin
